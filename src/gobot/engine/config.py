"""Generate KataGo analysis configs tuned to the host."""

from __future__ import annotations

from pathlib import Path
from typing import Any

# Values from the benchmark override these defaults (see data/engine.json).


def default_engine_settings(hw: dict[str, Any], backend: str) -> dict[str, Any]:
    mem_gb = float(hw.get("memory_gb") or 8)
    if mem_gb <= 8.5:
        cache_pow2 = 17
    elif mem_gb <= 16.5:
        cache_pow2 = 18
    else:
        cache_pow2 = 20
    if backend == "metal":
        threads, batch, mode = 8, 8, "gpu"
    else:
        cpus = int(hw.get("logical_cpus") or 4)
        threads, batch, mode = max(2, cpus), max(2, cpus), "none"
    return {
        "num_search_threads": threads,
        "nn_max_batch_size": batch,
        "metal_mode": mode,
        "nn_cache_pow2": cache_pow2,
        "num_analysis_threads": 2,
    }


def render_config(settings: dict[str, Any], backend: str) -> str:
    threads = int(settings["num_search_threads"])
    batch = int(settings["nn_max_batch_size"])
    cache = int(settings["nn_cache_pow2"])
    lines = [
        "# Generated by gobot (src/gobot/engine/config.py). Regenerated on every start;",
        "# edit data/engine.json or re-run scripts/benchmark.sh instead of this file.",
        "logToStderr = true",
        "logAllRequests = false",
        "logAllResponses = false",
        "logSearchInfo = false",
        "warnUnusedFields = true",
        "",
        "# All winrates, score leads and ownership are reported from BLACK's perspective.",
        "# The app relies on this and labels every number accordingly.",
        "reportAnalysisWinratesAs = BLACK",
        "",
        "# Search limits are set per query (overrideSettings.maxTime / maxVisits).",
        "maxVisits = 10000000",
        "maxTime = 6.0",
        "",
        f"numAnalysisThreads = {int(settings.get('num_analysis_threads', 2))}",
        f"numSearchThreadsPerAnalysisThread = {threads}",
        f"nnMaxBatchSize = {batch}",
        f"nnCacheSizePowerOfTwo = {cache}",
        f"nnMutexPoolSizePowerOfTwo = {max(10, cache - 3)}",
        "nnRandomize = true",
    ]
    if backend == "metal":
        mode = settings.get("metal_mode", "gpu")
        lines += ["", "# Metal backend (Apple Silicon)"]
        if mode == "mux":
            lines += [
                "numNNServerThreadsPerModel = 4",
                "metalDeviceToUseThread0 = 0",
                "metalDeviceToUseThread1 = 0",
                "metalDeviceToUseThread2 = 100",
                "metalDeviceToUseThread3 = 100",
            ]
        elif mode == "ane":
            lines += ["numNNServerThreadsPerModel = 1", "metalDeviceToUseThread0 = 100"]
        else:
            lines += ["numNNServerThreadsPerModel = 1", "metalDeviceToUseThread0 = 0"]
    elif backend == "eigen":
        eigen_threads = settings.get("num_eigen_threads")
        if eigen_threads:
            lines += ["", f"numEigenThreadsPerModel = {int(eigen_threads)}"]
    return "\n".join(lines) + "\n"


def write_config(path: Path, settings: dict[str, Any], backend: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_config(settings, backend))
    return path
